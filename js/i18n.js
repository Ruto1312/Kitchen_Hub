var LANG = "en";
try { LANG = localStorage.getItem("kitchenHavenLang") || ((navigator.language||"").indexOf("my")===0 ? "my" : "en"); } catch (e) {}
if (!TEXT[LANG]) LANG = "en";
function t(key, vars){
  var s = (TEXT[LANG][key] !== undefined ? TEXT[LANG][key] : TEXT.en[key]) || key;
  if (vars) Object.keys(vars).forEach(function(k){ s = s.split("{"+k+"}").join(vars[k]); });
  return s;
}
/* Counts in Burmese digits when Burmese is selected (prices stay as $0.00) */
function num(n){ return LANG==="my" ? String(n).replace(/[0-9]/g,function(d){return "၀၁၂၃၄၅၆၇၈၉"[d]}) : String(n); }
function pText(id, field, fallback){ return (LANG==="my" && PRODUCT_MY[id] && PRODUCT_MY[id][field]) || fallback; }
function applyStaticText(){
  document.documentElement.lang = LANG==="my" ? "my" : "en";
  document.body.classList.toggle("lang-my", LANG==="my");
  [].forEach.call(document.querySelectorAll("[data-i]"),function(el){ el.innerHTML = t(el.getAttribute("data-i")); });
  [].forEach.call(document.querySelectorAll("[data-i-ph]"),function(el){ el.placeholder = t(el.getAttribute("data-i-ph")); });
  [].forEach.call(document.querySelectorAll("[data-i-aria]"),function(el){ el.setAttribute("aria-label", t(el.getAttribute("data-i-aria"))); });
  [].forEach.call(document.querySelectorAll("[data-lang]"),function(b){ b.setAttribute("aria-pressed", b.getAttribute("data-lang")===LANG ? "true" : "false"); });
}
